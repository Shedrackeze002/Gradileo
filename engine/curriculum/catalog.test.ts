// The skill catalogue (catalog.ts) is generated from the generators: `npm run catalog` rewrites it,
// and this test fails when it is out of date.
import { describe, expect, it } from 'vitest';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ALL_SKILLS } from './all.ts';
import { COURSES } from './index.ts';

function render(): string {
  const order = new Map(COURSES.filter((c) => !c.map).flatMap((c) => c.lessons.flatMap((l) => l.skills)).map((id, i) => [id, i]));
  const rows = [...ALL_SKILLS]
    .sort((a, b) => (order.get(a.id) ?? 1e9) - (order.get(b.id) ?? 1e9))
    .map(({ id, name, description, outcomes, lessonId, format, calculator }) => JSON.stringify({ id, name, description, outcomes, lessonId, format, ...(calculator ? { calculator } : {}) }));
  return `// Generated by \`npm run catalog\` from the question generators. Do not edit by hand.
import type { SkillInfo } from '../types.ts';

export const SKILL_CATALOG: SkillInfo[] = [
${rows.map((r) => `  ${r},`).join('\n')}
];
`;
}

describe('skill catalogue', () => {
  it('matches the generators (run `npm run catalog` after changing a skill)', () => {
    const path = join(__dirname, 'catalog.ts');
    const want = render();
    if (process.env.UPDATE_CATALOG) writeFileSync(path, want);
    expect(readFileSync(path, 'utf8')).toBe(want);
  });
});
