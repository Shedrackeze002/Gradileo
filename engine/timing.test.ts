import { describe, expect, it } from 'vitest';
import { DEFAULT_SETTINGS, type AssignmentContent } from './assemble.ts';
import { adviseSettings, classPace, customMinutes, estimateWork, timeLimitFor } from './timing.ts';

const content = (patch: Partial<AssignmentContent> = {}): AssignmentContent => ({
  sections: [{ skillId: 'm8-pythagoras-leg', count: 4, difficulty: 'mixed' }],
  custom: [{ id: 'q1', kind: 'manual', prompt: 'Explain.', points: 4 }],
  ...patch,
});

describe('working time', () => {
  it('adds each question’s time: generated by difficulty, the teacher’s own by kind and points', () => {
    expect(customMinutes({ kind: 'mc' })).toBe(1);
    expect(customMinutes({ kind: 'manual', points: 4 })).toBe(8);
    // Mixed ramps 1, 2, 3, 2: 1.5 + 2.5 + 4 + 2.5 = 10.5, plus 8 for the written response.
    expect(estimateWork(content())).toEqual({ minutes: 19, fromClass: false });
  });

  it('uses the class’s own pace on a skill once there is enough of a record', () => {
    const sub = (ms: number[]) => ({ status: 'submitted', items: ms.map(() => ({ skillId: 'm8-pythagoras-leg', seed: 1, difficulty: 2 as const })), responses: Object.fromEntries(ms.map((t, i) => [i, { timeMs: t }])) });
    const pace = classPace([sub([60_000, 120_000, 180_000]), sub([120_000, 2_000, 3_600_000, 120_000]), { ...sub([600_000]), status: 'in_progress' }]);
    // Too quick (2 s), too long (an hour) and unfinished attempts are left out: the median of 1, 2, 3, 2, 2 minutes.
    expect(pace.get('m8-pythagoras-leg')).toBe(2);
    expect(classPace([sub([60_000, 60_000])]).size).toBe(0);
    // 2 × (0.8 + 1 + 1.3 + 1) = 8.2, plus 8 for the written response.
    expect(estimateWork(content(), pace)).toEqual({ minutes: 16, fromClass: true });
  });

  it('gives a time limit with half as long again to spare', () => {
    expect(timeLimitFor(19)).toBe(30);
    expect(timeLimitFor(6)).toBe(10);
    expect(timeLimitFor(200)).toBe(120);
  });
});

describe('suggested settings', () => {
  it('times a quiz, with one attempt, no hints and shuffled questions', () => {
    const a = adviseSettings('quiz', content(), { ...DEFAULT_SETTINGS.homework });
    expect(a.minutes).toBe(19);
    expect(a.settings).toEqual({ timeLimitMinutes: 30, attempts: 1, feedback: 'after_submit', hints: false, retrySimilar: false });
    expect(a.shuffle).toBe(true);
    expect(a.reasons[0]).toMatch(/^Time limit 30 min: half as long again/);
  });

  it('leaves homework untimed, and suggests nothing a teacher already has', () => {
    const a = adviseSettings('homework', content(), { ...DEFAULT_SETTINGS.quiz });
    expect(a.settings).toMatchObject({ timeLimitMinutes: null, attempts: 3, feedback: 'instant', hints: true, retrySimilar: true });
    expect(a.shuffle).toBeUndefined();
    expect(adviseSettings('homework', content(), { ...DEFAULT_SETTINGS.homework }).settings).toEqual({});
    // "Try a similar question" needs generated questions.
    expect(adviseSettings('practice', content({ sections: [] }), { ...DEFAULT_SETTINGS.practice }).settings).toEqual({ retrySimilar: false });
  });
});
